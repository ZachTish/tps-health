import type { TPSHealthSettings } from './types';
import { calculatedFoodLogKeys } from './food-log-presentation';
import { foodNutrientBaseFormula, foodPortionBaseFormulas } from './food-base-formulas';
import { CORE_NUTRIENT_KEYS, EXTRA_NUTRIENT_KEYS } from './nutrients';

/** Explicit conversion only. Preserve every unrelated value and the existing body. */
export function foodLogUpgrade(frontmatter: Record<string, unknown>, body: string, settings: TPSHealthSettings, embed: string) {
  const calculated = new Set(calculatedFoodLogKeys(settings).map(key => key.toLowerCase()));
  const removed = Object.keys(frontmatter).filter(key => calculated.has(key.toLowerCase()));
  const hasEmbed = [...body.matchAll(/```base[^\n]*\n([\s\S]*?)\n```/gu)].some(match => /"?healthServings"?\s*:/u.test(match[1]));
  return {
    frontmatter: Object.fromEntries(Object.entries(frontmatter).filter(([key]) => !calculated.has(key.toLowerCase()))),
    body: hasEmbed ? body : body + embed,
    changed: removed.length > 0 || !hasEmbed,
    removed,
  };
}

/** Upgrade only exact expressions previously generated by Health; custom edits
 * and every other Base field/view remain owned by the user.
 */
export function upgradeFoodBaseFormulas(base: Record<string, any>, settings: TPSHealthSettings): Record<string, any> | null {
  if (!base?.formulas || typeof base.formulas !== 'object' || Array.isArray(base.formulas)) return null;
  const replacements = new Map<string, string>();
  for (const key of [...CORE_NUTRIENT_KEYS, ...EXTRA_NUTRIENT_KEYS]) {
    const current = foodNutrientBaseFormula(settings, key);
    const stored = `note[${JSON.stringify((settings.nativeRecordProperties as any)?.[key] || key)}]`;
    // 10.1–10.3 formula: a copied field was required before scaling the linked food.
    const legacy = current.replace(`note[${JSON.stringify(settings.nativeRecordProperties?.food || 'food')}].isEmpty() && `, '')
      .replace('if(formula.healthServings != null', `if(${stored} != null && formula.healthServings != null`);
    replacements.set(legacy, current);
  }
  let changed = false;
  const formulas = { ...base.formulas };
  for (const [name, value] of Object.entries(formulas)) {
    if (typeof value !== 'string') continue;
    let next = value;
    for (const [old, current] of replacements) next = next.replace(old, current);
    if (name === 'healthPortionStatus' && value === foodPortionBaseFormulas(settings).healthPortionStatus
      .replace('"Link a food"', '"Saved totals — link a food to scale"').replace('"Missing food"', '"Missing food — saved totals"')) next = foodPortionBaseFormulas(settings).healthPortionStatus;
    if (next !== value) {formulas[name] = next; changed = true;}
  }
  return changed ? {...base, formulas} : null;
}

/** A one-time edit uses the existing Vault.process boundary. Backup precedes the
 * write; the source and open-editor guard are checked again inside the callback.
 */
export async function commitFoodUpgrade(options: {
  source: string; next: string; allowed: () => boolean;
  backup: () => Promise<void>;
  process: (callback: (current: string) => string) => Promise<unknown>;
}): Promise<boolean> {
  if (options.source === options.next) return false;
  if (!options.allowed()) throw new Error('This file is excluded or has unsaved edits. Nothing changed.');
  await options.backup();
  await options.process(current => {
    if (current !== options.source || !options.allowed()) throw new Error('This file changed while preparing the conversion. Nothing changed.');
    return options.next;
  });
  return true;
}
